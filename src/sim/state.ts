import type { Azimuth, Vec2, Vec3 } from './geometry';
import type { RngState } from './rng';
import type { BehaviorState } from './behavior/types';
import type { FofState } from './fof/types';
import type { PathPoint } from './bridge-navigation';

// Mutable simulation state (docs/adr/0004). Plain data only: no classes,
// closures or host objects, so it can be cloned, serialized and hashed.
// Collections are arrays in a fixed (scenario) order, so iteration is deterministic.

declare const brand: unique symbol;
type Brand<T, B extends string> = T & { readonly [brand]: B };

export type SoldierId = Brand<string, 'SoldierId'>;
export type OrgUnitId = Brand<string, 'OrgUnitId'>;
export type WaypointId = Brand<string, 'WaypointId'>;
export type EngagementAreaId = Brand<string, 'EngagementAreaId'>;

export const soldierId = (id: string): SoldierId => id as SoldierId;
export const orgUnitId = (id: string): OrgUnitId => id as OrgUnitId;
export const waypointId = (id: string): WaypointId => id as WaypointId;
export const engagementAreaId = (id: string): EngagementAreaId => id as EngagementAreaId;

export type Side = 'BLUEFOR' | 'OPFOR';

/**
 * A soldier's posture. In combat it scales the hit probability of shots at
 * the soldier (`CombatConfig.postureHitMultipliers`); OPFOR soldiers drop
 * prone as a reaction (docs/adr/0019). It does not change movement or line of sight.
 */
export type Posture = 'standing' | 'kneeling' | 'prone';

/**
 * Every soldier starts `active`. An `incapacitated` soldier (combat v1,
 * docs/adr/0019) no longer moves, fires, reacts or escapes, and is not a
 * target; it stays where it fell.
 */
export type SoldierStatus = 'active' | 'incapacitated';

/**
 * An organizational echelon label (e.g. "squad", "fireTeam"), defined by the
 * organization template the scenario was built from (docs/adr/0012). Labels
 * only: the simulation attaches no behavior to them.
 */
export type Echelon = string;

/** A map point of a soldier's route. Z always comes from the terrain. */
export interface Waypoint extends Readonly<Vec2> {
  /** Stable identifier, chosen by whoever authored the orders (e.g. the trainee's plan). */
  readonly id: WaypointId;
}

/**
 * Orders as given: the trainee's intent. Never modified by the simulation;
 * progress is tracked separately in `ActiveOrders`.
 */
export interface Orders {
  /** Points to move through, in order. May be empty (turn in place to `finalFacing`). */
  readonly waypoints: readonly Waypoint[];
  /** Azimuth to face once the last waypoint is reached. */
  readonly finalFacing: Azimuth;
  /**
   * Follow the roads to waypoints on a road (docs/adr/0043): OPFOR route
   * orders. Absent: every leg is planned off road.
   */
  readonly followRoads?: boolean;
}

/**
 * Behavior of a soldier with orders (a soldier without orders is idle):
 * `moving` toward `waypoints[nextWaypointIndex]`, then `facing` (turning to
 * `finalFacing`), then `inPosition`.
 */
export type OrdersBehavior = 'moving' | 'facing' | 'inPosition';

/** Orders being executed, with progress. */
export interface ActiveOrders {
  readonly orders: Orders;
  /** Index of the waypoint being moved to; equals `waypoints.length` once all are reached. */
  nextWaypointIndex: number;
  behavior: OrdersBehavior;
  /**
   * Generated by navigation, not trainee intent (docs/adr/0011): for each
   * waypoint, the turn points walked on the way to it from the previous one
   * (or from where the orders were given). Empty for a straight leg. Points
   * on a bridge's deck carry its height (`z`, docs/adr/0043).
   */
  readonly legPaths: readonly (readonly PathPoint[])[];
  /** Index into `legPaths[nextWaypointIndex]` of the next turn point. */
  nextTurnIndex: number;
  /**
   * Ground speed for these orders, in metres per second, when not the world's
   * movement speed (a fleeing soldier's, docs/adr/0019). Absent otherwise.
   */
  readonly speed?: number;
}

/** An individual soldier: the unit of simulation. */
export interface Soldier {
  readonly id: SoldierId;
  readonly side: Side;
  /** The soldier's immediate unit (e.g. their fire team, or the squad for a squad leader). */
  readonly unitId: OrgUnitId;
  /**
   * Z is the surface the soldier stands on: the terrain elevation at (x, y),
   * or a bridge's deck while crossing it (docs/adr/0043).
   */
  position: Vec3;
  /** Facing. While moving it turns toward the direction of travel at a limited rate. */
  azimuth: Azimuth;
  posture: Posture;
  status: SoldierStatus;
  /** `null` while idle. */
  orders: ActiveOrders | null;
}

/**
 * A node in an organization tree (squad, fire team, …). Units are structure,
 * not simulated entities: they have no position and never act. Membership is
 * recorded on soldiers (`Soldier.unitId`); a unit's members include those of
 * its descendant units.
 */
export interface OrgUnit {
  readonly id: OrgUnitId;
  readonly echelon: Echelon;
  readonly parentId: OrgUnitId | null;
  /** Leader, if any. Always a member of this unit or one of its descendants. */
  leaderId: SoldierId | null;
}

/**
 * A map polygon watched for soldiers of one side entering it (docs/adr/0010).
 * Geometry and monitoring only: what an entry means (e.g. springing an ambush)
 * is decided outside the simulation.
 */
export interface EngagementArea {
  readonly id: EngagementAreaId;
  /** A simple polygon of at least three map points; the boundary belongs to the area. */
  readonly vertices: readonly Vec2[];
  /** Soldiers of this side entering the area produce `engagementAreaEntered` events. */
  readonly monitoredSide: Side;
}

/** Why an engagement ended (docs/adr/0019), in the order the conditions are checked. */
export type EngagementEndReason =
  /** Every OPFOR soldier is incapacitated. */
  | 'allOpforIncapacitated'
  /** Every OPFOR soldier not incapacitated has escaped (at least one escaped). */
  | 'opforEscaped'
  /** Every BLUEFOR soldier is incapacitated. */
  | 'allBluforIncapacitated'
  /** No soldier on either side is still able to fire (see `isCombatCapable`). */
  | 'noCombatCapable'
  /** The configured maximum duration has passed. */
  | 'timeLimit';

/**
 * What a combatant is doing in the engagement:
 *
 * - `engaging`: BLUEFOR, firing at valid targets as its cadence allows;
 * - `awaitingReaction`: OPFOR before its reaction delay has passed; keeps
 *   doing what it did (e.g. walking its route) and does not fire;
 * - `prone`: OPFOR that dropped prone under fire; stays in place and returns fire;
 * - `fleeing`: OPFOR running away from the threat; does not fire;
 * - `escaped`: OPFOR that got far enough from where it started running;
 *   out of the engagement, not a target;
 * - `incapacitated`: out of the engagement, not a target.
 */
export type CombatBehavior =
  'engaging' | 'awaitingReaction' | 'prone' | 'fleeing' | 'escaped' | 'incapacitated';

/** An OPFOR soldier's reaction to the ambush (docs/adr/0028). */
export type OpforReaction = 'prone' | 'flee';

/** Per-soldier combat counts. */
export interface CombatantStats {
  shotsFired: number;
  /** Shots by this soldier that hit. */
  hits: number;
  /** Enemies this soldier incapacitated. */
  incapacitations: number;
  /** Shots that hit this soldier. */
  timesHit: number;
}

/** A soldier's part in the engagement. Every soldier of the scenario has one, in soldier order. */
export interface Combatant {
  readonly soldierId: SoldierId;
  readonly side: Side;
  /** The weapon fired (the soldier's primary weapon), or `null` when unarmed or unknown. */
  readonly weaponProfileRef: string | null;
  behavior: CombatBehavior;
  /**
   * OPFOR: the reaction it had, once it has reacted: `flee` when it was not
   * under fire, `reactionIfUnderFire` when it was. `null` before it reacts,
   * and for BLUEFOR.
   */
  reaction: OpforReaction | null;
  /** OPFOR: the reaction drawn at the start, taken if it is under fire when it reacts. */
  readonly reactionIfUnderFire: OpforReaction | null;
  /** Whether any shot has been fired at this soldier. */
  underFire: boolean;
  /** OPFOR: where it started running, once fleeing; escape is measured from there. */
  fleeFrom: Vec2 | null;
  /** OPFOR: when the reaction happens (simulation seconds); `null` for BLUEFOR. */
  readonly reactAtSeconds: number | null;
  /** Whether a flee found no route and the soldier dropped prone instead. */
  fleeBlocked: boolean;
  /** Time of the next firing opportunity, or `null` when the soldier does not fire. */
  nextShotSeconds: number | null;
  /** When the soldier escaped or was incapacitated. */
  outAtSeconds: number | null;
  stats: CombatantStats;
}

/** The engagement that follows the ambush (docs/adr/0019). Absent before it begins. */
export interface EngagementState {
  readonly startTick: number;
  readonly startSeconds: number;
  /** `startSeconds` + the configured maximum duration. */
  readonly endsBySeconds: number;
  combatants: Combatant[];
  /** Set when the engagement ends; combat stops then. */
  end: {
    readonly tick: number;
    readonly atSeconds: number;
    readonly reason: EngagementEndReason;
  } | null;
}

export interface SimState {
  /** Number of completed ticks. Simulation time is `tick / tickRateHz`. */
  tick: number;
  rng: RngState;
  units: OrgUnit[];
  soldiers: Soldier[];
  engagementAreas: EngagementArea[];
  /**
   * The engagement, once begun (`beginEngagement`). The property is absent
   * before then, so states without combat encode and hash as before it existed.
   */
  engagement?: EngagementState;
  /**
   * Unit tasks and the Marines they steer (docs/behavior-lab/03). Absent
   * until the first unit order, so states without one hash as before.
   */
  behavior?: BehaviorState;
  /**
   * A force-on-force experiment's state (docs/behavior-lab/force-on-force).
   * Absent unless the world has a force-on-force setup.
   */
  fof?: FofState;
}

/** Read-only view of simulation state handed to code outside the simulation. */
export type DeepReadonly<T> = T extends
  string | number | boolean | bigint | symbol | null | undefined
  ? T
  : T extends readonly (infer U)[]
    ? readonly DeepReadonly<U>[]
    : { readonly [K in keyof T]: DeepReadonly<T[K]> };

export function findSoldier(state: SimState, id: SoldierId): Soldier | undefined {
  return state.soldiers.find((s) => s.id === id);
}
